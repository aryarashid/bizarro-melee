export function pickRandomItemDef(rng = Math.random, excludeContainers = false) {
  const pool = excludeContainers ? ITEM_LIST.filter((i) => i.category !== 'container') : ITEM_LIST;
  const totalWeight = pool.reduce((sum, item) => sum + (item.weight || 5), 0);
  let r = rng() * totalWeight;
  for (const item of pool) {
    r -= (item.weight || 5);
    if (r <= 0) return item;
  }
  return pool[pool.length - 1];
}
